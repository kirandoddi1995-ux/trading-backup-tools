class _Parser(argparse.ArgumentParser):
    def error(self, message: str) -> NoReturn:
        raise ValueError('INVALID_ARGUMENTS')


def fixture_diagnostic(raw: bytes) -> dict[str, Any]:
    """Project only allow-listed phases and bounded numeric exit status."""
    failures = re.findall(rb'^FIXTURE_FAILURE:([a-z0-9_]+):([0-9]{1,3})$', raw, re.MULTILINE)
    if len(failures) != 1:
        return dict(failing_case=None, fixture_exit_code=None)
    phase, code = failures[0]
    if phase.decode('ascii') not in (*CASES, 'cluster_shutdown') or not 1 <= int(code) <= 255:
        return dict(failing_case=None, fixture_exit_code=None)
    return dict(failing_case=phase.decode('ascii'), fixture_exit_code=int(code))


def docker_args(name: str) -> tuple[str, ...]:
    if re.fullmatch('live-backup-synthetic-[a-f0-9]{32}', name) is None:
        raise ValueError('SYNTHETIC_NAME_REQUIRED')
    return ('create', '--pull=never', '--name', name, '--platform', 'linux/amd64', '--network', 'none',
        '--user', 'postgres', '--read-only', '--cap-drop', 'ALL',
        '--security-opt', 'no-new-privileges', '--memory', '512m', '--memory-swap', '512m',
        '--pids-limit', '64', '--cpus', '1', '--restart', 'no', '--log-driver', 'none',
        '--tmpfs', '/tmp:rw,nosuid,nodev,size=384m,mode=1777',
        '--entrypoint', '/bin/bash', IMAGE, '-c', SCRIPT)


def main(argv: Sequence[str] | None = None) -> int:
    name: str | None = None
    docker: str | None = None
    config: str | None = None
    result = io.BytesIO()
    stage = 'PREVIEW'
    report: dict[str, Any]
    exit_code = 0
    try:
        parser = _Parser(description=__doc__)
        parser.add_argument('--execute', action='store_true')
        parser.add_argument('--confirm-disposable', action='store_true')
        args = parser.parse_args(argv)
        if not (args.execute and args.confirm_disposable):
            print(json.dumps(dict(status='PREVIEW', network_requests=0, writes=0,
                                  native_invocations=0, hosted_changes=0)))
            return 0
        docker = shutil.which('docker')
        if not docker or not Path(docker).is_absolute():
            raise ValueError('DOCKER_UNAVAILABLE')
        # Caller supplies an already-pulled digest; never pull automatically.
        env = {key: value for key, value in os.environ.items()
               if key.upper() in ('PATH', 'SYSTEMROOT', 'WINDIR', 'TEMP', 'TMP', 'HOME', 'USERPROFILE')}
        # Never connect to an ambient remote Docker context/host or credential store.
        endpoint = 'npipe:////./pipe/dockerDesktopLinuxEngine' if os.name == 'nt' else 'unix:///var/run/docker.sock'
        config = tempfile.mkdtemp(prefix='synthetic-backup-empty-docker-config-')
        env['DOCKER_CONFIG'] = config
        name = 'live-backup-synthetic-' + uuid.uuid4().hex
        created = io.BytesIO()
        stage = 'CREATE_SYNTHETIC_CONTAINER'
        stream_process((docker, '--config', config, '--host', endpoint, *docker_args(name)), env=env,
                       sink=created, maximum=256, seconds=30)
        if re.fullmatch(rb'[a-f0-9]{64}\s*', created.getvalue()) is None:
            raise ValueError('CONTAINER_ID_UNVERIFIED')
        stage = 'RUN_SYNTHETIC_FIXTURE'
        stream_process((docker, '--config', config, '--host', endpoint, 'start', '--attach', name), env=env,
                       sink=result, maximum=4096, seconds=180)
        expected = ''.join('CASE:' + case + '\n' for case in CASES) + 'SYNTHETIC_NATIVE_BACKUP_CASES_PASSED\n'
        if result.getvalue() != expected.encode('ascii'):
            raise ValueError('SYNTHETIC_CHECK_UNVERIFIED')
        report = dict(status='SYNTHETIC_NATIVE_LOGICAL_RESTORE_PASSED',
            cases={case: True for case in CASES}, hosted_changes=0,
            private_restore_verified=False, windows_console_verified=False,
            custody_verified=False, deletion_authorised=False)
    except BaseException as error:
        completed = tuple(case for case in CASES
                          if ('CASE:' + case + '\n').encode('ascii') in result.getvalue())
        report = dict(status='BLOCKED', code='SYNTHETIC_BACKUP_STOP_REVIEW', stage=stage,
            reason=public_code(error), last_completed_case=completed[-1] if completed else None,
            **fixture_diagnostic(result.getvalue()),
            raw_error_printed=False, private_restore_verified=False, hosted_changes=0)
        exit_code = 2
    finally:
        if name and docker and config:
            # Stop only this unique synthetic container; retain it, never prune.
            endpoint = 'npipe:////./pipe/dockerDesktopLinuxEngine' if os.name == 'nt' else 'unix:///var/run/docker.sock'
            try:
                subprocess.run((docker, '--config', config, '--host', endpoint, 'stop', '--time', '3', name),
                    stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                    timeout=10, check=False)
                state = io.BytesIO()
                stream_process((docker, '--config', config, '--host', endpoint, 'inspect',
                    '--format', '{{.State.Running}}', name), env=env, sink=state, maximum=64, seconds=5)
                if state.getvalue().strip() != b'false':
                    raise OSError('synthetic stop not verified')
                report['synthetic_container_stopped_verified'] = True
            except (OSError, subprocess.TimeoutExpired):
                report = dict(status='BLOCKED', code='SYNTHETIC_STOP_UNVERIFIED',
                    raw_error_printed=False, private_restore_verified=False, hosted_changes=0)
                exit_code = 2
            except ValueError:
                report = dict(status='BLOCKED', code='SYNTHETIC_STOP_UNVERIFIED',
                    raw_error_printed=False, private_restore_verified=False, hosted_changes=0)
                exit_code = 2
    if name is not None:
        report['synthetic_run_id'] = name.removeprefix('live-backup-synthetic-')
    print(json.dumps(report, sort_keys=True))
    return exit_code


if __name__ == '__main__':
    raise SystemExit(main())
